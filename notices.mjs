// Collects the licence texts of everything bundled into Inkwell, straight from the installed packages,
// so the notices always match the versions that were actually built in.
import fs from 'node:fs';
import path from 'node:path';

export function thirdPartyNotices(root) {
  const nm = (p) => path.join(root, 'node_modules', p);
  const read = (p) => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n').trim();
  const version = (pkg) => JSON.parse(fs.readFileSync(nm(`${pkg}/package.json`), 'utf8')).version;
  const parts = [
    { name: `PDF.js ${version('pdfjs-dist')}`, by: 'Mozilla Foundation', licence: 'Apache License 2.0', url: 'https://github.com/mozilla/pdf.js',
      use: 'Reads and draws PDF files.', files: ['pdfjs-dist/LICENSE'] },
    { name: 'Adobe CMap resources', by: 'Adobe Systems Incorporated', licence: 'BSD 3-Clause', url: 'https://github.com/adobe-type-tools/cmap-resources',
      use: 'Character maps for Chinese, Japanese and Korean text, shipped with PDF.js.', files: ['pdfjs-dist/cmaps/LICENSE'] },
    { name: 'Foxit standard fonts', by: 'Foxit Software', licence: 'BSD 3-Clause', url: 'https://github.com/mozilla/pdf.js/tree/master/external/standard_fonts',
      use: 'Stand-ins for the 14 standard PDF fonts, shipped with PDF.js.', files: ['pdfjs-dist/standard_fonts/LICENSE_FOXIT'] },
    { name: 'Liberation fonts', by: 'Red Hat, Inc. and others', licence: 'SIL Open Font License 1.1', url: 'https://github.com/liberationfonts/liberation-fonts',
      use: 'Stand-ins for the 14 standard PDF fonts, shipped with PDF.js.', files: ['pdfjs-dist/standard_fonts/LICENSE_LIBERATION'] },
    { name: 'OpenJPEG', by: 'the OpenJPEG contributors', licence: 'BSD 2-Clause', url: 'https://github.com/uclouvain/openjpeg',
      use: 'Decodes JPEG 2000 images, shipped with PDF.js.', files: ['pdfjs-dist/wasm/LICENSE_OPENJPEG', 'pdfjs-dist/wasm/LICENSE_PDFJS_OPENJPEG'] },
    { name: 'JBIG2 decoder', by: 'the PDFium and PDF.js authors', licence: 'see below', url: 'https://github.com/mozilla/pdf.js.jbig2',
      use: 'Decodes JBIG2 images, shipped with PDF.js.', files: ['pdfjs-dist/wasm/LICENSE_JBIG2', 'pdfjs-dist/wasm/LICENSE_PDFJS_JBIG2'] },
    { name: 'qcms', by: 'Mozilla Foundation and others', licence: 'MIT', url: 'https://github.com/FirefoxGraphics/qcms',
      use: 'Colour management, shipped with PDF.js.', files: ['pdfjs-dist/wasm/LICENSE_QCMS', 'pdfjs-dist/wasm/LICENSE_PDFJS_QCMS'] },
    { name: `pdf-lib ${version('@cantoo/pdf-lib')} (Cantoo fork)`, by: 'Andrew Dillon and Cantoo', licence: 'MIT', url: 'https://github.com/cantoo-scribe/pdf-lib',
      use: 'Writes the saved PDF.', files: ['@cantoo/pdf-lib/LICENSE.md'] },
    { name: `Lucide icons ${version('lucide-static')}`, by: 'the Lucide contributors', licence: 'ISC (parts MIT, from Feather)', url: 'https://lucide.dev',
      use: 'Toolbar icons.', files: ['lucide-static/LICENSE'] },
    { name: `Instrument Sans (Fontsource ${version('@fontsource-variable/instrument-sans')})`, by: 'the Instrument Sans Project Authors', licence: 'SIL Open Font License 1.1', url: 'https://github.com/Instrument/instrument-sans',
      use: 'The typeface of the interface.', files: ['@fontsource-variable/instrument-sans/LICENSE'] },
  ];
  let out = `# Third-party notices

Inkwell is built from the open-source projects below. Their code, fonts and data are bundled into
\`Inkwell.html\` and into the Windows app, and each is used under its own licence, reproduced here in full.

The Windows app also contains Electron (MIT licence) and Chromium. Their licence texts are installed
next to \`Inkwell.exe\` as \`LICENSE.electron.txt\` and \`LICENSES.chromium.html\`.

This file is generated by \`build.mjs\` from the installed packages. Do not edit it by hand.

| Component | Authors | Licence | Used for |
| --- | --- | --- | --- |
${parts.map((p) => `| [${p.name}](${p.url}) | ${p.by} | ${p.licence} | ${p.use} |`).join('\n')}
`;
  for (const p of parts) {
    out += `\n\n## ${p.name}\n\n${p.by}. ${p.url}\n`;
    for (const f of p.files) out += `\n\`\`\`text\n${read(nm(f)).replace(/```/g, "'''")}\n\`\`\`\n`;
  }
  return out;
}
